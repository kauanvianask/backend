// Tipos de Dados em Javascript
/// No javascript, tudo o que armazenamos em variaveis tem um tipo. Esses tipos definem o que podemos fazer com esses valores.q

//Principais tipos de dados em Javascript:
// 1. String (texto)
// 2. Number (números)
// 3. Boolean (verdadeiro ou falso)
// 4. Undefined (variável não definida)
// 5. Null (valor vazio ou nulo)
// 6. Object (objetos que agrupam valores e funções (informações e comportamentos))
// 7. Array (vetor)

// string (textos)
let chamado = "Viana: Jarvis, tudo bem?";
let mensagem = 'Jarvis: Seja bem vindo Viana!';

console.log(chamado);
console.log(mensagem);

// typeof() é uma função que retorna o tipo de dado da variável
console.log(typeof chamado);
console.log(typeof mensagem);

let mensagem2 = "Viana: Jarvis a nota para seu trabalho é ";
let soma = 5 + 5;
console.log(mensagem2 + soma);